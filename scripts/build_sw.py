"""
Writes sw.js, the service worker that makes FitCheck.AI open offline.

The precache list is every page plus the CSS, JS modules, fonts and icons
the pages need. The cache version is a hash of those files, so any change to
the app gives a new version and old caches are dropped. Run after editing any
page, stylesheet or script:

    python scripts/build_sw.py

tests/static/test_pages.py fails if sw.js is out of date.
Swayam Shakya
"""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def shell_files():
    files = sorted(p.name for p in ROOT.glob("*.html"))
    files += ["manifest.webmanifest"]
    for folder, patterns in (("assets/css", ["*.css"]), ("assets/js", ["**/*.js"]),
                             ("assets/fonts", ["*.woff2"]), ("assets/images", ["favicon*.png", "logo/*.png", "icons/*.png", "paint/*.svg"])):
        for pat in patterns:
            files += sorted(str(p.relative_to(ROOT)) for p in (ROOT / folder).glob(pat) if "vendor" not in p.parts)
    return files


def version(files):
    h = hashlib.sha256()
    for f in files:
        h.update(f.encode())
        h.update((ROOT / f).read_bytes())
    return h.hexdigest()[:12]


TEMPLATE = """// FitCheck.AI service worker: generated by scripts/build_sw.py, don't edit by hand.
// Pages and assets are fetched from the network first (so you always get the
// current app) and kept for offline use. Nothing from /api is ever cached:
// your wardrobe, photos and account stay on the server, not in this browser.
// Swayam Shakya

const VERSION = "fitcheck-__VERSION__";
const SHELL = __SHELL__;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(VERSION).then((cache) => cache.addAll(SHELL.map((f) => "/" + f))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith("fitcheck-") && k !== VERSION).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

function cacheable(request, url) {
  return request.method === "GET" && url.origin === self.location.origin
    && !url.pathname.startsWith("/api/") && url.pathname !== "/sw.js";
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (!cacheable(request, url)) return;          // API calls, other sites and uploads go straight to the network
  event.respondWith((async () => {
    try {
      const response = await fetch(request);
      if (response.ok && response.type === "basic") {
        const copy = response.clone();
        caches.open(VERSION).then((cache) => cache.put(request, copy));
      }
      return response;
    } catch (err) {
      const key = url.pathname === "/" ? "/index.html" : request;
      const cached = await caches.match(key, { ignoreSearch: request.mode === "navigate" });
      if (cached) return cached;
      if (request.mode === "navigate") return (await caches.match("/offline.html")) || Response.error();
      throw err;
    }
  })());
});
"""


def render():
    files = shell_files()
    return TEMPLATE.replace("__VERSION__", version(files)).replace("__SHELL__", json.dumps(files, indent=2))


if __name__ == "__main__":
    (ROOT / "sw.js").write_text(render(), encoding="utf-8")
    print(f"sw.js written: {len(shell_files())} files precached")
