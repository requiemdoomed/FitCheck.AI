"""
Writes assets/js/engine/data.js from the Python reference catalogue
(ml/fitcheck_ml/catalog.py and color.py), so the browser engine and the
training code always share one vocabulary.

    python scripts/build_engine_data.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "ml"))
from fitcheck_ml import catalog, color, recommender  # noqa: E402

data = {
    "CATEGORIES": catalog.CATEGORIES,
    "STYLES": catalog.STYLES,
    "OCCASIONS": catalog.OCCASIONS,
    "SEASONS": catalog.SEASONS,
    "WEATHER": catalog.WEATHER,
    "PALETTES": catalog.PALETTES,
    "SUBCATEGORIES": catalog.SUBCATEGORIES,
    "CATEGORY_DEFAULTS": catalog.CATEGORY_DEFAULTS,
    "OCCASION_RULES": {k: {"formality": list(v["formality"]), "sporty": v["sporty"]}
                       for k, v in catalog.OCCASION_RULES.items()},
    "STYLE_AFFINITY": [[a, b, v] for (a, b), v in catalog._STYLE_AFFINITY.items()],
    "NAMED_COLORS": color.NAMED_COLORS,
    "WEIGHTS": recommender.WEIGHTS,
    "SHORTLIST": recommender.SHORTLIST,
    "ML_POOL": recommender.ML_POOL,
    "RANDOM_POOL": recommender.RANDOM_POOL,
}
out = ROOT / "assets" / "js" / "engine" / "data.js"
out.write_text("// Generated by scripts/build_engine_data.py from ml/fitcheck_ml. Do not edit by hand.\n"
               + "".join(f"export const {k} = {json.dumps(v)};\n" for k, v in data.items()), encoding="utf-8")
print("wrote", out.relative_to(ROOT))
